const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
let writes = [], cleared = [];
const record = {rowNumber: 3, row: ['club','Club','Active','user'], sheet: {getRange: (...args) => ({setValues: values => writes.push({args,values})})}};
const ctx = vm.createContext({Utilities: {getUuid: () => 'salt'}});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../GAS_FINAL_DEPLOY.js'),'utf8'),ctx);
ctx.findUserRecord = id => id === 'club' ? record : null;
ctx.hashPin = pin => 'hashed:' + pin;
ctx.clearLiveUserCache = id => cleared.push(id);
ctx.sendResponse = (data, success=true) => ({data,success});
assert.equal(ctx.adminResetPin({authUser:{role:'user'},userId:'club'}).success,false);
assert.equal(writes.length,0);
assert.equal(ctx.adminResetPin({authUser:{role:'admin'},userId:'missing'}).success,false);
assert.equal(ctx.adminResetPin({authUser:{role:'admin'},userId:'club',newPin:'9876'}).success,true);
assert.equal(writes.length,1);
assert.deepEqual(writes[0].args,[3,5,1,5]);
assert.equal(writes[0].values[0][1],'hashed:0000');
assert.equal(writes[0].values[0][2],true);
assert.deepEqual(cleared,['club']);
record.row[3]='admin';
assert.equal(ctx.adminResetPin({authUser:{role:'admin'},userId:'club'}).success,false);
record.row[3]='user'; record.row[0]='daily';
assert.equal(ctx.adminResetPin({authUser:{role:'admin'},userId:'club'}).success,false);
assert.equal(writes.length,1);
assert.throws(()=>ctx.setPinForRecord(record,'0000',false),/PIN/);
console.log('PASS: admin-only, selected row only, hashed temporary 0000, forced change, cache invalidation, admin/daily excluded, normal weak-PIN rejection.');
